class UserLanguageStorage:
    """
    Хранилище выбранного языка пользователей в памяти текущего процесса.
    Изолировано по user_id.

    Примечание: при перезапуске процесса бота данные сбрасываются к дефолту ('ru').
    Для продакшн-окружения хранилище может быть заменено на Redis или БД
    без изменения интерфейса (get/set).
    """

    def __init__(self) -> None:
        self._user_languages: dict[int, str] = {}

    def get(self, user_id: int) -> str:
        return self._user_languages.get(user_id, "ru")

    def set(self, user_id: int, lang: str) -> None:
        if lang in ("ru", "kk"):
            self._user_languages[user_id] = lang


