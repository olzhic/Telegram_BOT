def t(key: str, lang: str = "ru", **kwargs: Any) -> str:
    """Получение локализованного текста по ключу с подстановкой параметров."""
    lang_code = lang if lang in ("ru", "kk") else "ru"
    entry = MESSAGES.get(key, {})
    text = entry.get(lang_code) or entry.get("ru", f"[{key}]")
    if kwargs:
        try:
            return text.format(**kwargs)
        except Exception:
            return text
    return text
